-- =============================================================================
--  P5.3：酒店知识库语料（RAG 的数据源）
--
--  ★ 设计原则和项目其它地方一致：MySQL 是真相，ES 是"可重建的派生索引"。
--    所以这里不建全文索引 —— 检索由 ES 做，这份表只负责"原文 + 引用来源"。
--    索引坏了/映射改了，从这张表重建一次就行。
--
--  ⚠️ 下面全部是【示例语料】，为演示检索与引用而编写，不是真实酒店的实际条款。
--     真实系统里这些文本来自酒店录入或合同附件。
--
--  为什么按"小节"切块（而不是按字数硬切）：
--    引用溯源要说得出"依据：XX 酒店 · 停车场"，而 200 字一硬切会把
--    "有 30 个车位、住店免费"切成两半，检索到一半反而答得含糊。
-- =============================================================================

USE `hotel_booking`;

CREATE TABLE IF NOT EXISTS `hotel_kb_doc` (
    `id`          bigint       NOT NULL AUTO_INCREMENT,
    `hotel_id`    bigint       NOT NULL COMMENT '所属酒店',
    `section`     varchar(64)  NOT NULL COMMENT '小节标题（引用时展示）',
    `doc_type`    varchar(32)  NOT NULL DEFAULT 'FACILITY' COMMENT 'CHECKIN 入住须知 / FACILITY 设施服务 / CANCEL 退订条款',
    `content`     text         NOT NULL COMMENT '正文，200~400 字',
    `is_deleted`  tinyint(1)   NOT NULL DEFAULT 0,
    `create_time` datetime     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `update_time` datetime     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_hotel_section` (`hotel_id`, `section`),
    KEY `idx_hotel` (`hotel_id`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '酒店知识库原文（ES 索引的真相来源）';

