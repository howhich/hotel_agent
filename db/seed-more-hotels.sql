SELECT '酒店' AS `项`, COUNT(*) AS `数量` FROM `hotel` WHERE `is_deleted` = 0
UNION ALL SELECT '房型', COUNT(*) FROM `room_type` WHERE `is_deleted` = 0
UNION ALL SELECT '价格日历', COUNT(*) FROM `room_price`
UNION ALL SELECT '知识库', COUNT(*) FROM `hotel_kb_doc` WHERE `is_deleted` = 0;

SELECT `city`, COUNT(*) AS `hotels` FROM `hotel` WHERE `is_deleted` = 0 GROUP BY `city` ORDER BY `city`;
