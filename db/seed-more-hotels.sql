-- -----------------------------------------------------------------------------
-- 3. 180 天价格日历（新 12 个房型）
--
--   ★ 把 base 价格作为递归 CTE 的一列带下去，而不是 CROSS JOIN 再关联：
--     `FROM ... CROSS JOIN (...) rt ON DUPLICATE KEY UPDATE ...` 里的 ON
--     会被 MySQL 当成 JOIN 的 ON 条件解析 —— 直接语法错误。（seed-p0.sql 里踩过）
--   周末上浮 50%，平日就是 base。
-- -----------------------------------------------------------------------------
INSERT INTO `room_price` (`room_type_id`, `stay_date`, `price`, `member_price`)
WITH RECURSIVE seed(room_type_id, base, n) AS (
    SELECT rt.`room_type_id`,
           CASE rt.`room_type_id`
                WHEN 2007 THEN 1200.00 WHEN 2008 THEN 2200.00
                WHEN 2009 THEN 1100.00 WHEN 2010 THEN 1100.00
                WHEN 2011 THEN  380.00 WHEN 2012 THEN  420.00
                WHEN 2013 THEN  900.00 WHEN 2014 THEN 1600.00
                WHEN 2015 THEN 1500.00 WHEN 2016 THEN 2600.00
                WHEN 2017 THEN  450.00 WHEN 2018 THEN  480.00
           END,
           0
    FROM `room_type` rt
    WHERE rt.`room_type_id` BETWEEN 2007 AND 2018
    UNION ALL
    SELECT room_type_id, base, n + 1 FROM seed WHERE n < 179
)
SELECT seed.`room_type_id`,
       DATE_ADD(CURDATE(), INTERVAL seed.`n` DAY),
       CASE WHEN DAYOFWEEK(DATE_ADD(CURDATE(), INTERVAL seed.`n` DAY)) IN (1, 7)
            THEN seed.`base` * 3 / 2
            ELSE seed.`base` END,
       NULL
FROM seed
ON DUPLICATE KEY UPDATE `price` = VALUES(`price`);

