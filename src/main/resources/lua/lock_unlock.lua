-- =============================================================================
--  安全释放锁：只有"自己加的锁"才能删
--
--  为什么必须用 Lua：
--    如果分两步（先 GET 比对我加的 token、再 DEL），这两步之间可能发生：
--      1. 我的锁 TTL 到期，Redis 自动删掉了它
--      2. 另一个实例抢到了同名锁（token 是它的）
--      3. 我执行 DEL —— 删掉了【别人的锁】
--    这一下就把互斥彻底破坏了，而且不会有任何报错。
--
--    Redis 的 Lua 是原子执行的，比对和删除之间不会插进别的命令，
--    所以「token 相同才删」这个动作必须写在脚本里。
--
--  KEYS[1]  锁的 key
--  ARGV[1]  我自己写进去的 token
--
--  返回：1 = 删掉了（锁是我的）；0 = 没删（锁不是我的，或者已经过期了）
-- =============================================================================

if redis.call('GET', KEYS[1]) == ARGV[1] then
    return redis.call('DEL', KEYS[1])
else
    return 0
end
